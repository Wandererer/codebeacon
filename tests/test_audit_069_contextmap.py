def _backend_graph_with_controllers() -> nx.DiGraph:
    """2 controller classes + 3 plain service classes + 1 entity, one project."""
    G = nx.DiGraph()
    G.add_node("b1", project="backend", type="class", label="UserController",
               annotations=["@RestController"], source_file="/repo/backend/UserController.java")
    G.add_node("b2", project="backend", type="class", label="OrderController",
               annotations=["@RestController"], source_file="/repo/backend/OrderController.java")
    G.add_node("b3", project="backend", type="class", label="UserService",
               annotations=["@Service"], source_file="/repo/backend/UserService.java")
    G.add_node("b4", project="backend", type="class", label="OrderService",
               annotations=["@Service"], source_file="/repo/backend/OrderService.java")
    G.add_node("b5", project="backend", type="class", label="PaymentGateway",
               annotations=[], source_file="/repo/backend/PaymentGateway.java")
    G.add_node("b6", project="backend", type="entity", label="User",
               source_file="/repo/backend/User.java")
    return G


def _render_claude_md(G, projects, tmp_path) -> str:
    cb = tmp_path / ".codebeacon"
    cb.mkdir()
    written = generate_context_map(G, cb, projects, targets=["CLAUDE.md"])
    return Path(written[0]).read_text(encoding="utf-8")


def test_projects_table_services_matches_architecture(tmp_path):
    G = _backend_graph_with_controllers()
    projects = [ProjectInfo(name="backend", path="/repo/backend",
                            framework="spring-boot", language="java",
                            signature_file="pom.xml")]
    text = _render_claude_md(G, projects, tmp_path)

    proj_row = re.search(r"\| backend \| spring-boot \| \d+ \| (\d+) \|", text)
    arch = re.search(r"\*\*backend\*\*:.*?\n\s*Routes: \d+ \| Services: (\d+) \|",
                     text, re.S)
    notes = re.search(r"\| backend \| (\d+) services", text)

    assert proj_row is not None and arch is not None and notes is not None
    # All three surfaces agree, and on services-ONLY (3, not 3+2 controllers).
    assert proj_row.group(1) == arch.group(1) == notes.group(1) == "3", (
        f"Projects={proj_row.group(1)} Notes={notes.group(1)} "
        f"Architecture={arch.group(1)} — expected all == 3 (services only)"
    )


