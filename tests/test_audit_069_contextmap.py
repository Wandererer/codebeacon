# A realistic hand-written CLAUDE.md (e.g. from Claude Code /init): generic
# headings that also appear in codebeacon output, but zero codebeacon signature.
_HANDWRITTEN = """\
# CLAUDE.md

Hand-written guidance. Checked into git by a human.

## Architecture

CRITICAL: the `auth` service is the ONLY component allowed to mint tokens.
This is a modular monolith; the billing package owns money.

## Common Commands

make deploy-prod   # requires 2 approvals — DO NOT run casually

## Gotchas

The staging DB is shared; truncating it breaks three other teams.
"""


class TestStripLeavesUserContentAlone:
    def test_handwritten_file_returned_unchanged(self):
        # No codebeacon fingerprint → 100% user content, nothing stripped.
        out = _strip_codebeacon_block(_HANDWRITTEN)
        for needle in (
            "ONLY component allowed to mint tokens",
            "modular monolith",
            "billing package owns money",
            "make deploy-prod",
            "requires 2 approvals",
            "## Architecture",
            "## Common Commands",
            "truncating it breaks three other teams",
        ):
            assert needle in out, f"lost user content: {needle!r}"

    def test_merge_preserves_all_user_sections(self, tmp_path):
        # _merge_content prepends the new block but must keep every user line.
        p = tmp_path / "CLAUDE.md"
        p.write_text(_HANDWRITTEN, encoding="utf-8")
        merged = _merge_content("# codebeacon block\n\n_Generated by [codebeacon](x)_", p)
        for needle in (
            "ONLY component allowed to mint tokens",
            "make deploy-prod",
            "requires 2 approvals",
            "## Architecture",
            "## Common Commands",
            "truncating it breaks three other teams",
        ):
            assert needle in merged, f"_merge_content dropped user content: {needle!r}"

    def test_pure_user_file_with_only_generated_footer_substring(self):
        # A user who *mentions* codebeacon in prose but has no block still keeps
        # their headings intact (footer signature present, but no start header →
        # nothing gets entered, so nothing is stripped).
        txt = _HANDWRITTEN + "\nWe run `codebeacon` weekly; see .codebeacon/wiki/ for the index.\n"
        out = _strip_codebeacon_block(txt)
        assert "ONLY component allowed to mint tokens" in out
        assert "make deploy-prod" in out


