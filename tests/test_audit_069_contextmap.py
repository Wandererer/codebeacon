def test_generate_context_map_preserves_handwritten_claude_md(tmp_path):
    # End-to-end via the public API against a hand-written CLAUDE.md.
    (tmp_path / ".codebeacon").mkdir()
    claude = tmp_path / "CLAUDE.md"
    claude.write_text(_HANDWRITTEN, encoding="utf-8")

    G = nx.DiGraph()
    G.add_node("n1", project="demo", type="class", label="AuthService",
               source_file=str(tmp_path / "auth.py"))
    projects = [ProjectInfo(name="demo", path=str(tmp_path), framework="fastapi",
                            language="python", signature_file="pyproject.toml")]

    generate_context_map(G, tmp_path / ".codebeacon", projects, targets=["CLAUDE.md"])

    after = claude.read_text(encoding="utf-8")
    for needle in (
        "ONLY component allowed to mint tokens",
        "make deploy-prod",
        "requires 2 approvals",
        "truncating it breaks three other teams",
    ):
        assert needle in after, f"generate_context_map wiped user content: {needle!r}"
    # And it actually prepended the generated block.
    assert "<!-- codebeacon:start -->" in after


