# ── G11 round-2: contextmap ↔ wiki controller-count parity ───────────────────

def test_bare_restcontroller_annotation_agrees_with_wiki():
    """A @RestController class NOT named *Controller must be classified the same
    way by contextmap (_collect_stats) and the wiki (_is_controller).

    The extractor emits the annotation WITHOUT the leading '@' (['RestController']),
    which the '@'-only _CONTROLLER_ANNS missed — contextmap called it a service
    while the wiki called it a controller, so CLAUDE.md and the wiki disagreed.
    """
    G = nx.DiGraph()
    # Mirrors extract_services output: annotation is the bare identifier.
    G.add_node("n1", project="svc", type="class", label="HealthEndpoint",
               annotations=["RestController"], source_file="/r/HealthEndpoint.java")
    G.add_node("n2", project="svc", type="class", label="BillingService",
               annotations=["Service"], source_file="/r/BillingService.java")

    ctx_services = _collect_stats(G)["svc"]["services"]
    wiki_services = sum(
        1 for _n, d in G.nodes(data=True)
        if d.get("type") == "class"
        and not _is_controller(d.get("label", ""), d.get("annotations", []))
    )
    # Both surfaces must count exactly one service (BillingService); the bare
    # @RestController HealthEndpoint is a controller on both.
    assert ctx_services == wiki_services == 1
    # And contextmap must NOT count the bare-annotation controller as a service.
    assert _collect_stats(G)["svc"]["controllers"] == 1


def test_restcontroller_parity_end_to_end_as_extracted(tmp_path):
    """End-to-end 'as extracted' pin: run the real Spring extractor, then assert
    the CLAUDE.md Services count equals the wiki service_count."""
    from codebeacon.extract.services import extract_services

    java = tmp_path / "HealthEndpoint.java"
    java.write_text(
        "package demo;\n"
        "@RestController\npublic class HealthEndpoint { public String ping(){return \"ok\";} }\n"
        "@Service\npublic class BillingService { public void charge(){} }\n",
        encoding="utf-8",
    )
    svcs, _ = extract_services(str(java), "spring-boot")
    G = nx.DiGraph()
    for s in svcs:
        G.add_node(s.class_name, project="backend", type="class", label=s.class_name,
                   annotations=list(s.annotations), source_file=s.source_file)

    projects = [ProjectInfo(name="backend", path=str(tmp_path), framework="spring-boot",
                            language="java", signature_file="pom.xml")]
    text = _render_claude_md(G, projects, tmp_path)

    proj_row = re.search(r"\| backend \| spring-boot \| \d+ \| (\d+) \|", text)
    wiki_service_count = sum(
        1 for _n, d in G.nodes(data=True)
        if d.get("type") == "class"
        and not _is_controller(d.get("label", ""), d.get("annotations", []))
    )
    assert proj_row is not None
    assert int(proj_row.group(1)) == wiki_service_count == 1


# ── G09 round-2: footer-anchored legacy strip ────────────────────────────────

class TestFooterAnchoredStrip:
    # (a) Hand-written file with a `.codebeacon/wiki/` mention AND its own
    # `## Lookup strategy`, but NO footer → returned 100% unchanged.
    _NO_FOOTER_WITH_WIKI = """\
# CLAUDE.md

## Lookup strategy

> Check `.codebeacon/wiki/` first, then our internal runbook.
> CRITICAL: production DB credentials live in Vault — NEVER commit them to git.
> On-call rotation: page #sre before touching the payment path.

## Deployment

make deploy-prod requires two approvals.
"""

    def test_no_footer_file_returned_unchanged(self):
        out = _strip_codebeacon_block(self._NO_FOOTER_WITH_WIKI)
        # Byte-for-byte unchanged (modulo the leading/trailing whitespace strip).
        assert out == self._NO_FOOTER_WITH_WIKI.strip()
        for needle in (
            "CRITICAL: production DB credentials",
            "page #sre before touching",
            "## Lookup strategy",
            ".codebeacon/wiki/",
            "make deploy-prod",
        ):
            assert needle in out, f"lost user content: {needle!r}"

    # (b) Fingerprinted file WITH a footer but NO Lookup header → the old block
    # is stripped from the first legacy heading through the footer, so a re-merge
    # does not duplicate the codebeacon content.
    _FOOTER_NO_LOOKUP = """\
# CLAUDE.md

## Projects

| demo | fastapi | 0 | 1 | 0 | 0 |

See .codebeacon/wiki/ for details.

## Architecture

**demo**: fastapi

_Generated by [codebeacon](https://x) · 2026-01-01_
"""

    def test_footer_without_lookup_heading_is_stripped(self):
        out = _strip_codebeacon_block(self._FOOTER_NO_LOOKUP)
        # Everything from the first legacy heading (## Projects) through the
        # footer is removed; only the user's `# CLAUDE.md` title survives.
        assert out == "# CLAUDE.md"
        assert "## Projects" not in out
        assert "_Generated by" not in out
        assert "| demo | fastapi | 0 | 1" not in out

    def test_merge_twice_has_no_duplication_for_footer_without_lookup(self, tmp_path):
        p = tmp_path / "CLAUDE.md"
        p.write_text(self._FOOTER_NO_LOOKUP, encoding="utf-8")
        new_block = (
            "# CLAUDE.md\n\n## Projects\n\n| demo | fastapi | 0 | 1 | 0 | 0 |\n\n"
            "_Generated by [codebeacon](y) · 2026-07-11_"
        )
        first = _merge_content(new_block, p)
        p.write_text(first, encoding="utf-8")
        second = _merge_content(new_block, p)

        # Single footer + single Projects table after re-merge (no duplication).
        assert first.count("_Generated by [codebeacon]") == 1
        assert second.count("_Generated by [codebeacon]") == 1
        assert second.count("## Projects") == 1

    # (c) Marker-delimited files still take the Format-1 path (footer inside the
    # block does not leak), and user content below the markers survives.
    def test_marker_file_with_footer_inside_block_unchanged_semantics(self):
        txt = (
            "<!-- codebeacon:start -->\n"
            "## Lookup strategy\n\n## Projects\n\n"
            "_Generated by [codebeacon](x) · 2026-01-01_\n"
            "<!-- codebeacon:end -->\n\n"
            "## My Notes\n\nkeep me.\n"
        )
        out = _strip_codebeacon_block(txt)
        assert "keep me." in out
        assert "## My Notes" in out
        assert "## Projects" not in out
        assert "_Generated by" not in out
        assert "codebeacon:start" not in out


# ── Determinism: _pick_example_note picks a stable key, not insertion order ───

def test_pick_example_note_is_insertion_order_independent():
    def build(order):
        G = nx.DiGraph()
        for nid, label, sf in order:
            G.add_node(nid, project="p", type="class", label=label, source_file=sf)
        return G

    fwd = build([("n1", "Zebra", "/r/Zebra.py"), ("n2", "Apple", "/r/Apple.py")])
    rev = build([("n2", "Apple", "/r/Apple.py"), ("n1", "Zebra", "/r/Zebra.py")])
    # min by (label, node_id): "Apple" wins regardless of insertion order.
    assert _pick_example_note(fwd, "p") == _pick_example_note(rev, "p") == "Apple.py.md"


def test_example_column_stable_across_node_order(tmp_path):
    def build(order):
        G = nx.DiGraph()
        for nid, label, sf in order:
            G.add_node(nid, project="p", type="class", label=label, source_file=sf)
        return G

    projects = [ProjectInfo(name="p", path="/r", framework="fastapi",
                            language="python", signature_file="pyproject.toml")]

    def example_cell(G, sub):
        cb = tmp_path / sub / ".codebeacon"
        cb.mkdir(parents=True)
        written = generate_context_map(G, cb, projects, targets=["CLAUDE.md"])
        text = Path(written[0]).read_text(encoding="utf-8")
        return re.search(r"\| p \|[^|]*\| `([^`]+)` \|", text).group(1)

    fwd = build([("n1", "Zebra", "/r/Zebra.py"), ("n2", "Apple", "/r/Apple.py")])
    rev = build([("n2", "Apple", "/r/Apple.py"), ("n1", "Zebra", "/r/Zebra.py")])
    assert example_cell(fwd, "a") == example_cell(rev, "b") == "Apple.py.md"
