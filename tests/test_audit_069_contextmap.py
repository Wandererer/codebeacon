"""Audit 0.6.9 regressions for codebeacon/contextmap/generator.py.

G09 — CLAUDE.md section wipe (data-loss, high):
    _strip_codebeacon_block flipped into delete-mode on any generic heading in
    _LEGACY_PATTERNS ("## Architecture", "## Common Commands", …). Those are
    exactly what Claude Code's /init writes, so a hand-authored CLAUDE.md had
    its user sections silently deleted on the FIRST (marker-less) scan. The fix
    gates the legacy heuristic behind a positive codebeacon fingerprint and
    anchors the strip to the Lookup-strategy header + footer.

G11 — inconsistent Services counts (medium):
    The Projects table and Step-2 Notes column folded controller classes into
    "Services" (services + controllers) while the Architecture section and the
    wiki reported services only, so one document disagreed with itself. The fix
    unifies every surface on services-only.

Round-2 fixups (0.6.9 adversarial review):
    G11 — contextmap _CONTROLLER_ANNS only held the '@'-prefixed / bracketed
    forms, but the Spring/NestJS extractors emit annotations WITHOUT the '@'
    (e.g. ['RestController']). So an annotation-only @RestController class that
    is NOT named *Controller was counted as a service by CLAUDE.md while the
    wiki (whose _CONTROLLER_ANNOTATIONS includes the bare forms) counted it as a
    controller — the two committed artifacts disagreed. contextmap now reuses
    wiki/generator._CONTROLLER_ANNOTATIONS so the counts always match.

    G09 — the marker-less legacy strip is now FOOTER-ANCHORED: it fires only
    when a "_Generated by [codebeacon]" footer exists, removing from the
    block-start heading (a Lookup header, else the first legacy heading) through
    the footer inclusive. A no-footer file is returned 100% unchanged; a
    fingerprinted file with a footer but no Lookup header is stripped (no more
    duplication on merge).

    _pick_example_note now picks deterministically (min by (label, node_id)) so
    the CLAUDE.md Example column no longer flips with graph insertion order.
"""
from __future__ import annotations

import re
from pathlib import Path

import networkx as nx

from codebeacon.common.types import ProjectInfo
from codebeacon.contextmap.generator import (
    _collect_stats,
    _merge_content,
    _pick_example_note,
    _strip_codebeacon_block,
    generate_context_map,
)
from codebeacon.wiki.generator import _is_controller


